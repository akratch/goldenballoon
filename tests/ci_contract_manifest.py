#!/usr/bin/env python3
"""The exact text this repository's release lanes are pinned to, as data.

`tests/check_ci_contract.py` used to carry these literals inline, which meant
that renaming a step, rewording a refusal message or bumping a pinned hash was
an edit inside a four-thousand-line test. The checking engine lives there; the
literals live here, so a wording change is a data change.

Two kinds of entry:

  * `Pin` — one exact substring a named file must contain (`must_contain`) or
    must never contain (`must_not_contain`), with the `reason` it is pinned.
    Pins are grouped; a `PinGroup` fixes the failure wording and whether the
    file is read verbatim or with shell/YAML comments stripped first.

  * `Control` — one deliberate break of a pin. A gate that cannot reject a
    regression is documentation, so every control must make its group's
    validator fail. Controls are the falsifying half of the pins above: when
    you change a pinned literal, change its control in the same edit.

`file` names a source in the engine's registry (`check_ci_contract.SOURCES`),
not a path, so one file is read once and every group refers to it the same way.

Computation stays in the engine. Version agreement, the three-way
kFrameLimitHelp comparison, ordering, occurrence counts, structural regexes,
the archive manifests and the tests/README coverage sweep are derived, not
transcribed, and none of them belong in this file.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def project_version() -> str:
    """The release version every lane must agree on, from its one definition."""
    text = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    match = re.search(r'set\(MDKR_VERSION "([^"]+)"', text)
    if match is None:
        raise AssertionError("CMakeLists.txt does not set MDKR_VERSION")
    return match.group(1)


VERSION = project_version()
RELEASE_TAG = f"v{VERSION}"


@dataclass(frozen=True)
class Pin:
    """One exact literal a source file must, or must never, contain."""

    file: str
    reason: str
    must_contain: str | None = None
    must_not_contain: str | None = None

    def __post_init__(self) -> None:
        if (self.must_contain is None) == (self.must_not_contain is None):
            raise AssertionError(
                f"{self.reason}: pin one of must_contain/must_not_contain"
            )

    @property
    def needle(self) -> str:
        """The pinned literal, whichever direction it is pinned in."""
        return self.must_contain if self.must_contain is not None else self.must_not_contain

    def holds(self, text: str) -> bool:
        """Whether `text` satisfies this pin."""
        if self.must_contain is not None:
            return self.must_contain in text
        return self.must_not_contain not in text


@dataclass(frozen=True)
class PinGroup:
    """Pins that share a source-reading mode and a failure wording."""

    subject: str
    message: str
    active_shell: bool
    pins: tuple[Pin, ...]

    def failures(self, read) -> list[str]:
        """Every pin in this group that the sources no longer satisfy."""
        return [
            self.message.format(reason=pin.reason, needle=pin.needle)
            for pin in self.pins
            if not pin.holds(read(pin.file, self.active_shell))
        ]


def _replace(text: str, old: str, new: str, count: int | None) -> str:
    """`str.replace`, with `None` meaning every occurrence."""
    return text.replace(old, new) if count is None else text.replace(old, new, count)


@dataclass(frozen=True)
class Control:
    """One deliberately broken source that its group's gate must reject."""

    name: str
    file: str
    old: str
    new: str
    count: int | None = None
    regex: bool = False
    flags: int = 0
    #: Further literal `(old, new, count)` rewrites of the same file, applied
    #: in order. Only a control that has to *move* a step rather than delete it
    #: needs more than the one rewrite above.
    then: tuple[tuple[str, str, int | None], ...] = ()

    def apply(self, sources: dict[str, str]) -> dict[str, str]:
        """`sources` with this control's deliberate break applied."""
        text = sources[self.file]
        if self.regex:
            broken = re.sub(
                self.old, self.new, text,
                count=0 if self.count is None else self.count,
                flags=self.flags,
            )
        else:
            broken = _replace(text, self.old, self.new, self.count)
        for old, new, count in self.then:
            broken = _replace(broken, old, new, count)
        return {**sources, self.file: broken}


@dataclass(frozen=True)
class ControlGroup:
    """Controls checked against one validator, with its escape wording."""

    summary: str
    controls: tuple[Control, ...]


